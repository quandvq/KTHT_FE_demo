import fs from 'node:fs';
import path from 'node:path';

function parseCSV(text) {
  const lines = [];
  let row = [];
  let field = '';
  let inQuotes = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    const next = text[i + 1];
    if (inQuotes) {
      if (c === '"' && next === '"') {
        field += '"';
        i++;
      } else if (c === '"') {
        inQuotes = false;
      } else {
        field += c;
      }
    } else {
      if (c === '"') {
        inQuotes = true;
      } else if (c === ',') {
        row.push(field);
        field = '';
      } else if (c === '\r' && next === '\n') {
        row.push(field);
        lines.push(row);
        row = [];
        field = '';
        i++;
      } else if (c === '\n' || c === '\r') {
        row.push(field);
        lines.push(row);
        row = [];
        field = '';
      } else {
        field += c;
      }
    }
  }
  if (field || row.length) {
    row.push(field);
    lines.push(row);
  }
  return lines;
}

const slugify = (value) =>
  value
    .replace(/đ/g, 'd')
    .replace(/Đ/g, 'd')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');

const csvPath = path.resolve('docs/source/thuoc_products_2026-11-06.csv');
const catalogPath = path.resolve('src/data/catalog.ts');

const csvRaw = fs.readFileSync(csvPath, 'utf8');
const rows = parseCSV(csvRaw);
const header = rows[0].map((h) => h.trim());
console.log('CSV header:', header);

const dataRows = rows.slice(1).filter((r) => r.length > 1 && r[0].trim());
console.log('Total CSV rows:', dataRows.length);

const colIdx = {};
header.forEach((name, idx) => {
  colIdx[name] = idx;
});

const newProducts = [];
for (const r of dataRows) {
  const id = r[colIdx.demo_id].trim();
  const name = r[colIdx.name].trim();
  const rawCategory = r[colIdx.category].trim();
  const brand = (r[colIdx.brand] || '').trim() || 'Đang cập nhật';
  const packageSize = (r[colIdx.package_size] || '').trim();
  const saleUnit = (r[colIdx.sale_unit] || '').trim();
  const price = Number(r[colIdx.price_vnd]) || 0;
  const currency = (r[colIdx.currency] || '').trim() || 'VND';
  const description = (r[colIdx.description] || '').trim();
  const sourceUrl = (r[colIdx.source_url] || '').trim() || 'https://www.pharmacity.vn/';
  const checkedDate = (r[colIdx.checked_date] || '').trim() || '2026-11-06';
  const priceStatus =
    (r[colIdx.price_status] || '').trim() ||
    'Giá hiển thị trên trang chi tiết; cần tư vấn dược sĩ khi mua';
  
  let imageUrl = (r[colIdx.image_url] || '').trim();
  if (id === 'PC-MED-50-012') {
    imageUrl = 'https://cdn.nhathuoclongchau.com.vn/unsafe/800x0/00500237_kem_boi_da_promethazin_10g_2303_63bb_large_511e9c072e.jpg';
  }
  const image = `/images/products/${id.toLowerCase()}.png`;

  // Preserve subcategory in tags, along with "Thuốc" and "Cần xác minh"
  const tagSet = new Set();
  if (rawCategory) tagSet.add(rawCategory);
  tagSet.add('Thuốc');
  tagSet.add('Cần xác minh');

  newProducts.push({
    id,
    slug: `${slugify(name)}-${id.toLowerCase()}`,
    name,
    category: 'Thuốc',
    brand,
    packageSize,
    saleUnit,
    price,
    currency,
    description,
    image,
    imageUrl,
    sourceUrl,
    checkedDate,
    priceStatus,
    verificationNote: 'Trang chi tiết; cần tư vấn dược sĩ khi mua',
    restricted: true,
    tags: Array.from(tagSet),
  });
}

console.log('Created new products:', newProducts.length);
console.log('Sample item 0:', JSON.stringify(newProducts[0], null, 2));
console.log('Sample item 49:', JSON.stringify(newProducts[49], null, 2));

// Read existing catalog
const catalogFile = fs.readFileSync(catalogPath, 'utf8');

// Match existing products array
const exportMatch = catalogFile.match(/export const catalog: readonly CatalogProduct\[\] = (\[[\s\S]*\]);/);
if (!exportMatch) {
  throw new Error('Could not match export const catalog in ' + catalogPath);
}

const existingCatalog = JSON.parse(exportMatch[1]);
console.log('Existing catalog items count:', existingCatalog.length);

// Check if any med products already exist
const existingIds = new Set(existingCatalog.map((p) => p.id));
const toAdd = newProducts.filter((p) => !existingIds.has(p.id));
console.log('Products to add (not yet in catalog):', toAdd.length);

const combined = [...existingCatalog, ...toAdd];
console.log('Combined catalog length:', combined.length);

// Generate new catalog.ts
const newCatalogContent = `// Generated by scripts/import-pharmacity-catalog.mjs. Do not hand-edit.
export type CatalogProduct = { id:string; slug:string; name:string; category:string; brand:string; packageSize:string; saleUnit:string; price:number; currency:string; description:string; image:string; imageUrl:string; sourceUrl:string; checkedDate:string; priceStatus:string; verificationNote:string; restricted:true; tags:readonly string[] };
export const catalog: readonly CatalogProduct[] = ${JSON.stringify(combined, null, 2)};
`;

fs.writeFileSync(catalogPath, newCatalogContent, 'utf8');
console.log('Successfully wrote combined catalog to', catalogPath);

