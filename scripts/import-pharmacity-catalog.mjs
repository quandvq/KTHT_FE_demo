import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const XLSX = require('xlsx');

const source = path.resolve('docs/source/pharmacity_products_2026-11-03.xlsx');
const imageDir = path.resolve('public/images/products');
const output = path.resolve('src/data/catalog.ts');
const reportPath = path.resolve('docs/source/catalog-import-report.json');
const workbook = XLSX.readFile(source);
const rows = XLSX.utils.sheet_to_json(workbook.Sheets[workbook.SheetNames[0]], { defval: '' });
const seen = new Set();
const slugify = value => value.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');
const excelDate = value => typeof value === 'number' ? XLSX.SSF.format('yyyy-mm-dd', value) : String(value || '');
const safeName = id => `${id.toLowerCase().replace(/[^a-z0-9-]/g, '-')}.png`;
await fs.mkdir(imageDir, { recursive: true });
const failures = [];
const products = [];
for (const row of rows) {
  const id = String(row.demo_id).trim();
  if (!id || seen.has(id)) throw new Error(`demo_id missing or duplicated: ${id}`);
  seen.add(id);
  const fileName = safeName(id);
  const localImage = `/images/products/${fileName}`;
  let image = localImage;
  try {
    const response = await fetch(String(row.image_url));
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const bytes = new Uint8Array(await response.arrayBuffer());
    if (!bytes.length) throw new Error('empty response');
    await fs.writeFile(path.join(imageDir, fileName), bytes);
  } catch (error) {
    image = '/images/products/fallback-product.svg';
    failures.push({ id, name: row.name, image_url: row.image_url, error: String(error.message || error) });
  }
  products.push({
    id, slug: `${slugify(row.name)}-${id.toLowerCase()}`, name: String(row.name), category: String(row.category),
    brand: String(row.brand || '').trim() || 'Đang cập nhật', packageSize: String(row.package_size || ''), saleUnit: String(row.sale_unit || ''),
    price: Number(row.price_vnd) || 0, currency: String(row.currency || 'VND'), description: String(row.description || ''),
    image, imageUrl: String(row.image_url || ''), sourceUrl: String(row.source_url || ''), checkedDate: excelDate(row.checked_date),
    priceStatus: String(row.price_status || ''), verificationNote: String(row.verification_note || ''),
    restricted: false, tags: []
  });
}
await fs.mkdir(path.dirname(output), { recursive: true });
await fs.writeFile(output, `// Generated by scripts/import-pharmacity-catalog.mjs. Do not hand-edit.\nexport type CatalogProduct = { id:string; slug:string; name:string; category:string; brand:string; packageSize:string; saleUnit:string; price:number; currency:string; description:string; image:string; imageUrl:string; sourceUrl:string; checkedDate:string; priceStatus:string; verificationNote:string; restricted:true; tags:readonly string[] };\nexport const catalog: readonly CatalogProduct[] = ${JSON.stringify(products, null, 2)};\n`, 'utf8');
await fs.writeFile(reportPath, JSON.stringify({ source: path.basename(source), rows: rows.length, uniqueIds: seen.size, imagesDownloaded: products.length - failures.length, imageFailures: failures.length, failures }, null, 2), 'utf8');
console.log(JSON.stringify({ rows: rows.length, uniqueIds: seen.size, imagesDownloaded: products.length - failures.length, imageFailures: failures.length }, null, 2));
